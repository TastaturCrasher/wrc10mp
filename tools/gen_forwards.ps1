# Generates src/winhttp_proxy/forwards.h: forwards every export of the system
# winhttp.dll that the proxy does not intercept itself.
param(
    [string]$Dumpbin = (Get-ChildItem 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Tools\MSVC\*\bin\Hostx64\x64\dumpbin.exe' | Select-Object -Last 1).FullName
)

$intercepted = @(
    'WinHttpConnect', 'WinHttpOpenRequest', 'WinHttpAddRequestHeaders', 'WinHttpSendRequest',
    'WinHttpReceiveResponse', 'WinHttpQueryHeaders', 'WinHttpQueryDataAvailable',
    'WinHttpReadData', 'WinHttpCloseHandle'
)

$out = Join-Path $PSScriptRoot '..\src\winhttp_proxy\forwards.h'
$lines = @('// Generated by tools/gen_forwards.ps1 - do not edit.', '#pragma once')
& $Dumpbin /exports "$env:SystemRoot\System32\winhttp.dll" | ForEach-Object {
    if ($_ -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]+\s+(\w+)') {
        $ordinal = $Matches[1]; $name = $Matches[2]
        if ($intercepted -notcontains $name) {
            # COM entry points must be PRIVATE and the linker wants no ordinal on them.
            $suffix = if ($name -like 'Dll*') { ',PRIVATE' } else { ",@$ordinal" }
            $lines += "#pragma comment(linker, `"/export:$name=\\\\.\\GLOBALROOT\\SystemRoot\\System32\\winhttp.dll.$name$suffix`")"
        }
    }
}
$lines | Set-Content -Encoding ascii $out
Write-Host "Wrote $($lines.Count - 2) forwards to $out"
